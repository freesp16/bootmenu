#!/usr/bin/env python3
"""Bake the boot menu's text faces into one 8-bit coverage atlas, written as a C header (src/gen/font_atlas.h).

The device has no font files and the menu must draw its first frame fast, so glyphs are rasterised here, on the PC,
once: the binary uploads the atlas as one GL_ALPHA texture and never touches FreeType. Faces are Inter (SIL OFL 1.1,
fonts/INTER-LICENSE.txt), as pinned subsets.

    python3 tools/make-font-atlas.py            # -> src/gen/font_atlas.h

Needs Pillow with FreeType (python3 -c "from PIL import ImageFont; print(ImageFont.core.freetype2_version)").
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"
OUT = ROOT / "src" / "gen" / "font_atlas.h"

# (C name, file, pixel size). The order is the FontId enum in src/bm.h.
FACES = [
    ("FONT_TITLE", "Inter-SemiBold.subset.ttf", 27),
    ("FONT_NAME", "Inter-SemiBold.subset.ttf", 22),
    ("FONT_BODY", "Inter-Regular.subset.ttf", 15),
    ("FONT_HINT", "Inter-Medium.subset.ttf", 14),
    ("FONT_CHIP", "Inter-SemiBold.subset.ttf", 11),
    ("FONT_ICON", "Inter-SemiBold.subset.ttf", 26),
    ("FONT_SPLASH", "Inter-SemiBold.subset.ttf", 30),
    ("FONT_HERO", "Inter-SemiBold.subset.ttf", 46),  # the splash tile's letter: capitals and digits only
]
HERO_ONLY = set(range(ord("0"), ord("9") + 1)) | set(range(ord("A"), ord("Z") + 1)) | {ord("?")}
EXTRA = [0x00B7, 0x2013, 0x2014, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193]
CODEPOINTS = list(range(0x20, 0x7F)) + EXTRA
ATLAS_W = 512
PAD = 1


def rasterise(font, ch):
    """Coverage bitmap of one glyph and its placement relative to the pen on the baseline."""
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    adv = font.getlength(ch)
    w, h = max(0, right - left), max(0, bottom - top)
    if w == 0 or h == 0:
        return None, left, top, adv
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    return img, left, top, adv


def main():
    glyphs = []  # (face index, cp, img, xoff, yoff, adv)
    metrics = []
    for fi, (_, file, size) in enumerate(FACES):
        font = ImageFont.truetype(str(FONTS / file), size)
        ascent, descent = font.getmetrics()
        # Height of a capital and of the x-height, for vertical centring of labels.
        cap = -font.getbbox("H", anchor="ls")[1]
        xh = -font.getbbox("x", anchor="ls")[1]
        metrics.append((size, ascent, descent, cap, xh))
        notdef = font.getmask("￿").getbbox()
        for cp in CODEPOINTS:
            if FACES[fi][0] == "FONT_HERO" and cp not in HERO_ONLY:
                continue
            img, xo, yo, adv = rasterise(font, chr(cp))
            if cp > 0x7E and img is not None and font.getmask(chr(cp)).getbbox() == notdef:
                continue  # not in the subset: the drawer falls back to '?'
            glyphs.append((fi, cp, img, xo, yo, adv))

    # Shelf packing, tallest first.
    order = sorted(range(len(glyphs)), key=lambda i: -(glyphs[i][2].height if glyphs[i][2] else 0))
    x = y = shelf = 0
    place = {}
    for i in order:
        img = glyphs[i][2]
        if img is None:
            place[i] = (0, 0, 0, 0)
            continue
        w, h = img.width + PAD, img.height + PAD
        if x + w > ATLAS_W:
            x, y, shelf = 0, y + shelf, 0
        place[i] = (x, y, img.width, img.height)
        x += w
        shelf = max(shelf, h)
    atlas_h = 1
    while atlas_h < y + shelf:
        atlas_h *= 2
    atlas = Image.new("L", (ATLAS_W, atlas_h), 0)
    for i, (fi, cp, img, *_rest) in enumerate(glyphs):
        if img is not None:
            atlas.paste(img, place[i][:2])

    lines = [
        "/* Generated by tools/make-font-atlas.py from Inter (SIL OFL 1.1, fonts/INTER-LICENSE.txt). Do not edit. */",
        "#ifndef BM_FONT_ATLAS_H",
        "#define BM_FONT_ATLAS_H",
        "#include <stdint.h>",
        f"#define FONT_ATLAS_W {ATLAS_W}",
        f"#define FONT_ATLAS_H {atlas_h}",
        f"#define FONT_FACES {len(FACES)}",
        "typedef struct { uint16_t cp; uint16_t x, y; uint8_t w, h; int8_t xoff, yoff; uint16_t adv64; } AtlasGlyph;",
        "typedef struct { uint8_t size, ascent, descent, cap, xheight; uint16_t first, count; } AtlasFace;",
    ]
    faces_c, glyph_c = [], []
    for fi, (name, file, size) in enumerate(FACES):
        mine = [i for i, g in enumerate(glyphs) if g[0] == fi]
        mine.sort(key=lambda i: glyphs[i][1])
        first = len(glyph_c)
        for i in mine:
            _, cp, _, xo, yo, adv = glyphs[i]
            px, py, pw, ph = place[i]
            glyph_c.append(f"{{0x{cp:04x},{px},{py},{pw},{ph},{xo},{yo},{round(adv * 64)}}}")
        s, a, d, cap, xh = metrics[fi]
        faces_c.append(f"{{{s},{a},{d},{cap},{xh},{first},{len(mine)}}} /* {name} {file} */")
    lines.append("static const AtlasFace font_faces[FONT_FACES] = {\n  " + ",\n  ".join(faces_c) + "\n};")
    lines.append("static const AtlasGlyph font_glyphs[] = {")
    for k in range(0, len(glyph_c), 6):
        lines.append("  " + ",".join(glyph_c[k:k + 6]) + ",")
    lines.append("};")
    data = atlas.tobytes()
    lines.append(f"static const uint8_t font_atlas[{len(data)}] = {{")
    for k in range(0, len(data), 32):
        lines.append("".join(f"{b}," for b in data[k:k + 32]))
    lines.append("};")
    lines.append("#endif")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(glyphs)} glyphs in {ATLAS_W}x{atlas_h} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
